"""Draw the Loupebox mark and wordmark once, and write every copy of them.

    python -m scripts.brand_art       # then: python -m scripts.generate_logos

The loupe (ring, check, handle) is defined by `lens()` as proportions of its radius, so the standalone icon
and the lens inside the wordmark are the same drawing at two sizes. The letters are outlined from Hanken
Grotesk (the UI font; LOUPE bold, BOX regular) so nothing needs the font at render time. Colors come from
web/src/tokens.css.

Writes:
  web/src/brandArt.tsx                           the React Mark and Wordmark (colored by CSS tokens)
  web/public/brand/loupebox-icon-{dark,light}    square icon art (dark has the tile background)
  web/public/brand/loupebox-wordmark-{dark,light}  transparent wordmark, used by the README

Needs fonttools and `npm ci` in web/ (the font files come from @fontsource/hanken-grotesk).
"""

# ruff: noqa: E501  (the generated SVG/JSX templates read better on one line)

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WEB = ROOT / "web"
FONTS = WEB / "node_modules/@fontsource/hanken-grotesk/files/hanken-grotesk-latin-{}-normal.woff"
TOKENS = WEB / "src/tokens.css"
BRAND = WEB / "public/brand"
CLASS = {"class": "mk-stroke"}  # the React copies take their color from CSS: --accent
NOTE = "<!-- Generated by scripts/brand_art.py. Do not edit. -->"

# Lens proportions (of its radius). The ring is a little heavier than a hairline so it holds up next to bold letters.
RING, CHECK, HANDLE_W, HANDLE_LEN = (
    0.175,
    0.116,
    0.29,
    0.629,
)  # HANDLE_LEN: how far the handle runs on x and on y
CHECK_PTS = ((-0.547, 0.0), (-0.182, 0.365), (0.547, -0.365))

# Wordmark layout, in the same units as the original artwork: cap height, baseline, lens radius and centre.
CAP, BASELINE, CENTER_Y, LENS_R = 77.0, 163.5, 125.0, 40.0
TRACKING, PAD_LEFT, PAD_RIGHT = (
    5.0,
    4.0,
    9.0,
)  # the handle sits right of the ring, so that side gets more room
WORD_BOX = (66, 130)  # viewBox y and height; the width follows the letters


def num(v: float) -> str:
    return f"{v:.2f}".rstrip("0").rstrip(".")


def lens(cx: float, cy: float, r: float) -> dict:
    """The loupe's three strokes, in SVG user units."""
    ring = RING * r
    off = 0.7071 * (r + ring / 2)
    return {
        "ring": {"cx": cx, "cy": cy, "r": r, "w": ring},
        "check": {"pts": [(cx + dx * r, cy + dy * r) for dx, dy in CHECK_PTS], "w": CHECK * r},
        "handle": {
            "x1": cx + off,
            "y1": cy + off,
            "x2": cx + off + HANDLE_LEN * r,
            "y2": cy + off + HANDLE_LEN * r,
            "w": HANDLE_W * r,
        },
    }


def el(tag: str, attrs: dict, jsx: bool) -> str:
    """One SVG element; in JSX mode the attribute names are camelCased (class -> className)."""
    camel = lambda k: "className" if k == "class" else re.sub(r"-(\w)", lambda m: m[1].upper(), k)
    return f"<{tag} " + " ".join(f'{camel(k) if jsx else k}="{v}"' for k, v in attrs.items()) + " />"


def lens_markup(g: dict, stroke: dict, jsx: bool = False) -> str:
    """The three strokes as SVG (a stroke color) or JSX (a CSS class), with matching attributes."""
    ring, check, handle = g["ring"], g["check"], g["handle"]
    round_ = {"stroke-linecap": "round"}
    pts = " ".join(f"{num(x)},{num(y)}" for x, y in check["pts"])
    parts = [
        (
            "circle",
            {
                **stroke,
                "cx": num(ring["cx"]),
                "cy": num(ring["cy"]),
                "r": num(ring["r"]),
                "fill": "none",
                "stroke-width": num(ring["w"]),
            },
        ),
        (
            "polyline",
            {
                **stroke,
                "points": pts,
                "fill": "none",
                "stroke-width": num(check["w"]),
                **round_,
                "stroke-linejoin": "round",
            },
        ),
        (
            "line",
            {
                **stroke,
                **{k: num(handle[k]) for k in ("x1", "y1", "x2", "y2")},
                "stroke-width": num(handle["w"]),
                **round_,
            },
        ),
    ]
    return ("\n" + " " * 6 * jsx).join(el(tag, attrs, jsx) for tag, attrs in parts)


def letters() -> tuple[list[str], float, float]:
    """Outlined LOUPE + BOX with a gap for the lens where the O of LOUPE goes: (paths, lens centre x, width)."""
    from fontTools.pens.svgPathPen import SVGPathPen
    from fontTools.pens.transformPen import TransformPen
    from fontTools.ttLib import TTFont

    fonts = {w: TTFont(str(FONTS).format(w)) for w in (700, 400)}
    paths, x, lens_x = [], 0.0, None
    for ch, weight in [(c, 700) for c in "LOUPE"] + [(c, 400) for c in "BOX"]:
        if ch == "O" and lens_x is None:
            x += PAD_LEFT
            lens_x = x + LENS_R * (1 + RING / 2)
            x += 2 * LENS_R * (1 + RING / 2) + PAD_RIGHT + TRACKING
            continue
        font = fonts[weight]
        scale = CAP / font["OS/2"].sCapHeight
        name = font.getBestCmap()[ord(ch)]
        glyphs = font.getGlyphSet()
        pen = SVGPathPen(glyphs, ntos=num)
        glyphs[name].draw(TransformPen(pen, (scale, 0, 0, -scale, x, BASELINE)))
        paths.append(pen.getCommands())
        x += font["hmtx"][name][0] * scale + TRACKING
    return paths, lens_x, x - TRACKING


def token_colors() -> dict[str, dict[str, str]]:
    css = TOKENS.read_text()
    out = {}
    for theme in ("dark", "light"):
        block = css[css.index(f':root[data-theme="{theme}"] {{') :].split("}")[0]
        out[theme] = dict(re.findall(r"(--[\w-]+):\s*(#[0-9A-Fa-f]{6})", block))
    return out


def render() -> dict[Path, str]:
    paths, lens_x, width = letters()
    word_lens = lens(lens_x, CENTER_Y, LENS_R)
    icon_lens = lens(110, 110, 62)
    colors = token_colors()
    vb_pad = 6
    word_vb = f"{-vb_pad} {WORD_BOX[0]} {num(width + 2 * vb_pad)} {WORD_BOX[1]}"
    files: dict[Path, str] = {}
    for theme, c in colors.items():
        letters_svg = "".join(f'<path d="{d}" />' for d in paths)
        files[BRAND / f"loupebox-wordmark-{theme}.svg"] = (
            f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{word_vb}" role="img" aria-label="Loupebox">\n{NOTE}\n'
            f'<g fill="{c["--text"]}">{letters_svg}</g>\n{lens_markup(word_lens, {"stroke": c["--accent"]})}\n</svg>\n'
        )
        tile = f'<rect width="250" height="250" fill="{c["--bg"]}" />\n' if theme == "dark" else ""
        # "<!-- Lens" is the marker scripts/generate_logos.py splits on to derive the tile and maskable icons.
        files[BRAND / f"loupebox-icon-{theme}.svg"] = (
            f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 250 250" role="img" aria-label="Loupebox">\n{NOTE}\n'
            f"{tile}<!-- Lens -->\n{lens_markup(icon_lens, {'stroke': c['--accent']})}\n</svg>\n"
        )
    group = "".join(f'          <path d="{d}" />\n' for d in paths)
    files[WEB / "src/brandArt.tsx"] = f"""// Generated by scripts/brand_art.py. Do not edit.
// The mark and wordmark, colored from the tokens (--accent for the loupe, --text for the letters).

export function Mark({{ size, className = "" }}: {{ size: number; className?: string }}) {{
  return (
    <svg className={{`logo logo-mark ${{className}}`}} width={{size}} height={{size}} viewBox="40 40 170 170" aria-hidden focusable="false">
      {lens_markup(icon_lens, CLASS, jsx=True)}
    </svg>
  );
}}

export function Wordmark({{ height }}: {{ height: number }}) {{
  return (
    <svg className="wordmark-art" viewBox="{word_vb}" height={{height}} role="img" aria-label="Loupebox" focusable="false">
      <g className="mk-letters">
{group}      </g>
      {lens_markup(word_lens, CLASS, jsx=True)}
    </svg>
  );
}}
"""
    return files


def main() -> int:
    if not Path(str(FONTS).format(700)).exists():
        print("Hanken Grotesk not found: run `npm ci` in web/ first.", file=sys.stderr)
        return 1
    for path, text in render().items():
        path.write_text(text)
        print(f"{path.relative_to(ROOT)} written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
